# Додавання нових тем до існуючої бази

existing_topics = {item["id"] for item in topics}
existing_questions = {item["id"] for item in questions}

for index, (
    topic_id,
    name,
    skill_id,
    skill_name,
    prerequisites,
    error_description,
    recommendation,
    exercises
) in enumerate(EXTRA_TOPICS):

    if topic_id not in existing_topics:
        topics.append({
            "id": topic_id,
            "name": name
        })

    skills[skill_id] = {
        "name": skill_name,
        "topic": topic_id,
        "prerequisites": prerequisites
    }

    error_id = topic_id + "_mistake"

    misconceptions[error_id] = {
        "topic": topic_id,
        "description": error_description,
        "recommendation": recommendation
    }

    for level, (question, answer, wrong_answer) in enumerate(
        exercises, start=1
    ):
        question_id = 101 + index * 3 + level - 1

        if question_id in existing_questions:
            continue

        questions.append({
            "id": question_id,
            "question": question,
            "topic": topic_id,
            "skill": skill_id,
            "difficulty": level,
            "correct_answer": answer,
            "common_mistakes": (
                {wrong_answer: error_id}
                if wrong_answer else {}
            )
        })
